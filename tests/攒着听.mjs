// 攒着听（issue #39）：这一批群消息值不值得叫醒它
import { 该放行缓冲 } from '../lib/host.js'

let 挂 = 0
const 报 = (标, 过, 细) => {
  if (!过) 挂++
  console.log((过 ? 'PASS  ' : 'FAIL  ') + 标 + (细 ? '  :: ' + 细 : ''))
}

const 批 = (...文们) => 文们.map((t) => ({ 文字: t }))

const 两问 = 该放行缓冲(批('在吗？', '有人吗？'))
报('两条问话 → 放行', 两问.放行 === true, 两问.说)

const 一問多句 = 该放行缓冲(批('今天吃啥', '不知道啊', '谁去？'))
报('三条里有一条问话 → 放行', 一問多句.放行 === true, 一問多句.说)

const 闲聊 = 该放行缓冲(批('哈哈', '笑死', '确实', '真的假的', '绝了'))
报('纯闲聊 → 不放行（攒着）', 闲聊.放行 === false, 闲聊.说)

const 一条问 = 该放行缓冲(批('谁去？'))
报('只有一条问话、也没聊起来 → 不放行', 一条问.放行 === false, 一条问.说)

const 空 = 该放行缓冲([])
报('空的 → 不放行', 空.放行 === false, 空.说)

报('非数组也不会炸', 该放行缓冲(null).放行 === false, '')

console.log('')
console.log(挂 === 0 ? '全过' : ('挂了 ' + 挂 + ' 条'))
process.exit(挂 === 0 ? 0 : 1)
